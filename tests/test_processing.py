import pytest

from src.processing import filter_by_state, sort_by_date


def test_filter_by_state_execute(my_state_1):
    assert filter_by_state(my_state_1) == [
        {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
        {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
    ]


def test_filter_by_state_canceled(my_state_2):
    assert filter_by_state(my_state_2, "CANCELED") == [
        {"id": 594286727, "state": "CANCELED", "date": "2016-11-16T21:27:25.241689"},
        {"id": 615364591, "state": "CANCELED", "date": "2019-12-24T08:21:33.419441"},
    ]


@pytest.mark.parametrize(
    "my_list, expected",
    [
        (
            [
                {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
                {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
                {"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"},
                {"id": 615064591, "state": "CANCELED", "date": "2018-10-14T08:21:33.419441"},
            ],
            [
                {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
                {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
            ],
        ),
        ([], []),
    ],
)
def test_filter_by_state(my_list, expected):
    assert filter_by_state(my_list) == expected


